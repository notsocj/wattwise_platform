const data = Object.entries(icons).map(([component, name]) => {
  const icon = getIconData(solar, name);
  if (!icon) throw new Error(`Missing Solar icon for ${component}: ${name}`);
  const { attributes, body } = iconToSVG(icon);
  return `  ${component}: { viewBox: ${JSON.stringify(attributes.viewBox)}, body: ${JSON.stringify(body)} },`;
});

